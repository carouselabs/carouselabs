// scripts/comment-presets-sql.js — writes the SQL for the built-in comment
// presets from their one source each: LinkedIn's in
// scripts/seed-comment-profiles.js, X's in scripts/x-profile-presets.js.
//
//   node scripts/comment-presets-sql.js
//
// rewrites:
// - scripts/human-comment-profiles.sql: UPDATEs the presets' text in a live
//   database (the person runs it in Supabase). Only the text: who they're
//   default for, their order and recommended flags stay as they are.
// - scripts/seed-comment-profiles.sql: the LinkedIn presets for a new
//   database (the manual fallback for seed-comment-profiles.js).
// - the X presets block of scripts/x-extension-schema.sql, which creates them.
// browser-extension-comment/tests/unit/commentPresets.server.test.ts fails
// when any of the three no longer matches the data.
const fs = require("fs")
const path = require("path")
const { SYSTEM_PROFILES } = require("./seed-comment-profiles")
const { X_PRESETS } = require("./x-profile-presets")
const { REDDIT_PRESETS } = require("./reddit-profile-presets")

const text = (value) => (value == null ? "NULL" : `'${String(value).replace(/'/g, "''")}'`)
const array = (values) => `ARRAY[${(values || []).map(text).join(", ")}]::TEXT[]`
const bool = (value) => (value ? "true" : "false")

// The text fields, as one SET list.
function setText(preset) {
  return [
    `"name" = ${text(preset.name)}`,
    `"whoIAm" = ${text(preset.whoIAm)}`,
    `"goal" = ${text(preset.goal)}`,
    `"tone" = ${text(preset.tone)}`,
    `"length" = ${text(preset.length)}`,
    `"emoji" = ${text(preset.emoji || "None")}`,
    `"alwaysDo" = ${text(preset.alwaysDo)}`,
    `"neverDo" = ${text(preset.neverDo)}`,
    `"samples" = ${array(preset.samples)}`,
    `"updatedAt" = CURRENT_TIMESTAMP`,
  ].join(",\n    ")
}

function updates(table, presets) {
  return presets
    .map((preset) => `UPDATE "${table}" SET\n    ${setText(preset)}\n  WHERE "id" = ${text(preset.id)} AND "isSystem" = true;`)
    .join("\n\n")
}

// The rows' ids, for the closing check.
const ids = (presets) => presets.map((p) => text(p.id)).join(", ")

function updateSql({ linkedin, x }, header) {
  return `${header}
BEGIN;

-- ── LinkedIn (CommentProfile) ──
${updates("CommentProfile", linkedin)}

-- ── X (XProfile) ──
${updates("XProfile", x)}

COMMIT;

-- Check: ${linkedin.length} LinkedIn and ${x.length} X presets, every one just updated.
SELECT
  (SELECT count(*) FROM "CommentProfile" WHERE "isSystem" = true AND "id" IN (${ids(linkedin)}) AND "updatedAt" > now() - interval '5 minutes') AS "linkedinUpdated",
  (SELECT count(*) FROM "XProfile" WHERE "isSystem" = true AND "id" IN (${ids(x)}) AND "updatedAt" > now() - interval '5 minutes') AS "xUpdated";
`
}

const UPDATE_HEADER = `-- scripts/human-comment-profiles.sql — GENERATED by
-- scripts/comment-presets-sql.js from scripts/seed-comment-profiles.js and
-- scripts/x-profile-presets.js. Edit those, then re-run the generator.
--
-- Puts the rewritten built-in comment presets (2026-10-11: comments that
-- sound like a person, not AI) into the live database: all 11 LinkedIn
-- presets and all 7 X presets, by id. Same names, so nobody's default or
-- history changes; only what each preset tells the AI. Does not add or remove
-- any preset. Safe to re-run. No deploy needed for this part: the extensions
-- read presets from the database.
-- Undo: scripts/human-comment-profiles-rollback.sql.
`

function seedSql(linkedin) {
  const rows = linkedin.map(
    (p) =>
      `  (${[
        text(p.id),
        "NULL",
        text(p.name),
        text(p.whoIAm),
        text(p.goal),
        text(p.tone),
        text(p.length),
        text(p.emoji || "None"),
        text(p.language || "English"),
        text(p.alwaysDo),
        text(p.neverDo),
        array(p.samples),
        bool(p.isDefault),
        "true",
        bool(p.isRecommended),
        "0",
        "CURRENT_TIMESTAMP",
        "CURRENT_TIMESTAMP",
      ].join(", ")})`,
  )
  return `-- scripts/seed-comment-profiles.sql — GENERATED by
-- scripts/comment-presets-sql.js from scripts/seed-comment-profiles.js; edit
-- that, then re-run the generator.
--
-- Manual fallback for scripts/seed-comment-profiles.js: run this in the
-- Supabase SQL editor if that script can't reach the DB directly. Needs
-- scripts/comment-extension-schema.sql (the CommentProfile table) and
-- scripts/recommended-profiles-schema.sql (its isRecommended column) first.
-- Idempotent: ON CONFLICT (id) updates in place.

INSERT INTO "CommentProfile"
  ("id", "userId", "name", "whoIAm", "goal", "tone", "length", "emoji", "language", "alwaysDo", "neverDo", "samples", "isDefault", "isSystem", "isRecommended", "testsUsed", "createdAt", "updatedAt")
VALUES
${rows.join(",\n")}
ON CONFLICT (id) DO UPDATE SET
  "name" = EXCLUDED."name",
  "whoIAm" = EXCLUDED."whoIAm",
  "goal" = EXCLUDED."goal",
  "tone" = EXCLUDED."tone",
  "length" = EXCLUDED."length",
  "emoji" = EXCLUDED."emoji",
  "alwaysDo" = EXCLUDED."alwaysDo",
  "neverDo" = EXCLUDED."neverDo",
  "samples" = EXCLUDED."samples",
  "isSystem" = EXCLUDED."isSystem",
  "isRecommended" = EXCLUDED."isRecommended",
  "isDefault" = EXCLUDED."isDefault",
  "updatedAt" = CURRENT_TIMESTAMP;
`
}

// The INSERT that scripts/x-extension-schema.sql creates the X presets with
// (and scripts/reddit-extension-schema.sql the Reddit ones). Each row's
// createdAt is a second after the one before, which is the order
// GET /api/ext/<site>/profiles lists them in.
function presetInsertSql(table, site, presets) {
  const rows = presets.map(
    (p, i) => `  (${text(p.id)}, NULL, ${text(p.name)},
   ${text(p.whoIAm)},
   ${text(p.goal)},
   ${text(p.tone)}, ${text(p.length)}, ${text(p.emoji || "None")}, 'English',
   ${text(p.alwaysDo)},
   ${text(p.neverDo)},
   ${array(p.samples)},
   ${bool(p.isDefault)}, true, ${bool(p.isRecommended)}, CURRENT_TIMESTAMP + INTERVAL '${i + 1} second${i ? "s" : ""}', CURRENT_TIMESTAMP)`,
  )
  return `INSERT INTO "${table}"
  ("id", "userId", "name", "whoIAm", "goal", "tone", "length", "emoji", "language", "alwaysDo", "neverDo", "samples", "isDefault", "isSystem", "isRecommended", "createdAt", "updatedAt")
VALUES
${rows.join(",\n")}
ON CONFLICT ("id") DO UPDATE SET
  "name" = EXCLUDED."name",
  "whoIAm" = EXCLUDED."whoIAm",
  "goal" = EXCLUDED."goal",
  "tone" = EXCLUDED."tone",
  "length" = EXCLUDED."length",
  "emoji" = EXCLUDED."emoji",
  "alwaysDo" = EXCLUDED."alwaysDo",
  "neverDo" = EXCLUDED."neverDo",
  "samples" = EXCLUDED."samples",
  "isDefault" = EXCLUDED."isDefault",
  "isSystem" = EXCLUDED."isSystem",
  "isRecommended" = EXCLUDED."isRecommended",
  -- The list's order (GET /api/ext/${site}/profiles sorts by it): the times above
  -- are a second apart so the presets always show in the order written.
  "createdAt" = EXCLUDED."createdAt",
  "updatedAt" = CURRENT_TIMESTAMP;`
}

const X_SCHEMA = path.join(__dirname, "x-extension-schema.sql")
const X_BLOCK = /INSERT INTO "XProfile"[\s\S]*?"updatedAt" = CURRENT_TIMESTAMP;/
const REDDIT_SCHEMA = path.join(__dirname, "reddit-extension-schema.sql")
const REDDIT_BLOCK = /INSERT INTO "RedditProfile"[\s\S]*?"updatedAt" = CURRENT_TIMESTAMP;/

function files() {
  const data = { linkedin: SYSTEM_PROFILES, x: X_PRESETS }
  const schema = fs.readFileSync(X_SCHEMA, "utf8").replace(/\r\n/g, "\n")
  if (!X_BLOCK.test(schema)) throw new Error("x-extension-schema.sql: X presets INSERT not found")
  const redditSchema = fs.readFileSync(REDDIT_SCHEMA, "utf8").replace(/\r\n/g, "\n")
  if (!REDDIT_BLOCK.test(redditSchema)) throw new Error("reddit-extension-schema.sql: Reddit presets INSERT not found")
  return {
    [path.join(__dirname, "human-comment-profiles.sql")]: updateSql(data, UPDATE_HEADER),
    [path.join(__dirname, "seed-comment-profiles.sql")]: seedSql(SYSTEM_PROFILES),
    // A function, so "$" in the SQL is never read as a replacement pattern.
    [X_SCHEMA]: schema.replace(X_BLOCK, () => presetInsertSql("XProfile", "x", X_PRESETS)),
    [REDDIT_SCHEMA]: redditSchema.replace(REDDIT_BLOCK, () => presetInsertSql("RedditProfile", "reddit", REDDIT_PRESETS)),
  }
}

module.exports = { files, updateSql }

if (require.main === module) {
  for (const [file, content] of Object.entries(files())) {
    // Keeps the line endings the file has (CRLF in a Windows checkout).
    const crlf = fs.existsSync(file) && fs.readFileSync(file, "utf8").includes("\r\n")
    fs.writeFileSync(file, crlf ? content.replace(/\r?\n/g, "\r\n") : content)
    console.log(`Wrote ${path.relative(process.cwd(), file)}`)
  }
}
