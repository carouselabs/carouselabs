// Renders the Saved comments announcement (emails/SavedCommentsLaunchEmail.tsx)
// into lib/readyEmailsSavedComments.ts, the fixed HTML and words that
// lib/readyEmails.ts lists as a ready-made email (Admin → Broadcasts →
// Ready-made emails). After changing the email, run:
//   node scripts/ready-email-saved-comments.mjs
// tests/ready-email-saved-comments.test.tsx fails while the module is out of
// date. Its pictures are in public/images/email/saved-comments/ and load from
// the live site, so they show only once deployed.
import { writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { createJiti } from "jiti"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const OUT = path.join(ROOT, "lib/readyEmailsSavedComments.ts")

// Links in an email always point at the live site (emails/theme.ts).
delete process.env.NEXT_PUBLIC_APP_URL

const jiti = createJiti(import.meta.url, { alias: { "@": ROOT }, jsx: true })
const React = await import("react")
const { render } = await import("@react-email/render")
const { SavedCommentsLaunchEmail, SAVED_COMMENTS_SUBJECT, SAVED_COMMENTS_PREVIEW } = await jiti.import(
  path.join(ROOT, "emails/SavedCommentsLaunchEmail.tsx"),
)

const element = React.createElement(SavedCommentsLaunchEmail)
const html = await render(element)
// The words from the greeting on (not the logo's link), each step's number
// apart from its title ("1. Save it once", not "1Save it once").
const plain = await render(element, { plainText: true })
const text = plain
  .slice(plain.indexOf("Hi {{firstName}}"))
  .replace(/^(\d)(?=\S)/gm, "$1. ")
  .trim()

if (/<script/i.test(html)) throw new Error("The email has a <script>: emails can't")
if (Buffer.byteLength(html) > 100_000) throw new Error("The email is over 100 KB: Gmail would clip it")
if (!html.includes("{{firstName}}")) throw new Error("The email lost its {{firstName}}")

writeFileSync(
  OUT,
  `// lib/readyEmailsSavedComments.ts — generated by scripts/ready-email-saved-comments.mjs
// from emails/SavedCommentsLaunchEmail.tsx (don't edit by hand: change the email
// there and run it again). {{firstName}} is filled in for each person;
// lib/readyEmails.ts lists it.
export const SAVED_COMMENTS_SUBJECT = ${JSON.stringify(SAVED_COMMENTS_SUBJECT)}

export const SAVED_COMMENTS_PREVIEW = ${JSON.stringify(SAVED_COMMENTS_PREVIEW)}

export const SAVED_COMMENTS_HTML = ${JSON.stringify(html)}

export const SAVED_COMMENTS_TEXT = ${JSON.stringify(text)}
`,
)
console.log(`wrote ${path.relative(ROOT, OUT)} (${(Buffer.byteLength(html) / 1024).toFixed(1)} KB of HTML)`)
